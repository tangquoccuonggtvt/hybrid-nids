"""Fuse Suricata EVE alerts with Random Forest AI alerts.

This script is intentionally small and auditable for the thesis deployment
pipeline. It does not change the trained model. It correlates two alert streams:

- Suricata EVE JSON/JSONL alerts, usually from ``eve.json``.
- AI alerts generated by ``nids_detector.py`` in ``logs/ai_alerts.jsonl``.

The output is a JSONL file that can be ingested by Logstash/Kibana as the
Hybrid-NIDS alert stream.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import re
from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any, Iterable


SEVERITY_RANK = {"LOW": 0, "MEDIUM": 1, "HIGH": 2, "CRITICAL": 3}
AI_CRITICAL_SCORE = 0.95
AI_HIGH_MARGIN = 0.10



@dataclass(frozen=True)
class NormalizedAlert:
    source: str
    timestamp: datetime
    raw: dict[str, Any]
    src_ip: str
    dst_ip: str
    dst_port: int
    protocol: str

    @property
    def key(self) -> tuple[str, str, int, str]:
        return (self.src_ip, self.dst_ip, self.dst_port, self.protocol)

    @property
    def host_key(self) -> tuple[str, str, str]:
        return (self.src_ip, self.dst_ip, self.protocol)


@dataclass(frozen=True)
class LabAttackWindow:
    scenario: str
    src_ip: str
    dst_ip: str
    proto: str
    port_ranges: tuple[tuple[int, int], ...]
    start: datetime | None
    end: datetime | None


